/**
 * A Symbol is a token identified only by its color (a CSS3 color name).
 * @author  Gian Franco Arroyo Perez, Nicolas Deaza Casasbuenas
 * @version 1.0
 */
public class Symbol{

    private String color;


    public Symbol(String color){
        this.color = color;
    }


    public String getColor(){
        return color;
    }
}
